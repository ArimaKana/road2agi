export const CAMPAIGN: Level[] = [CACHE_PORT, MIRROR_LIBRARY, GRADIENT_FORGE, ZERO_DOMAIN];
// Who comes in each room is kept in one table (spec 8.9) rather than beside the maps.
for (const level of CAMPAIGN) for (const room of level.rooms) {
  const waves = ENCOUNTERS[room.id];
  if (!waves) continue;
  room.waves = waves.map(wave => {
    const units = unitsOf(wave), boss = units.find(kind => kind in BOSS_LIFE);
    return { count: units.length, hp: 0, units, ...(boss ? { boss: true, bossHp: BOSS_LIFE[boss] } : {}) };
  });
}
