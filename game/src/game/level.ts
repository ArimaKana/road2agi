import { BOSS_LIFE, ENCOUNTERS, unitsOf } from './encounters.ts';
import type { EnemyKind } from './enemies.ts';
// In a map # is wall, o a crate, . floor, < the door in and > the door out. Any other letter marks the floor a trap of that name covers.
// Rows run along x and go down in z, so on screen the top row is the upper right edge and the left column the upper left edge. Doors in sit on the near edges, doors out on the far ones.
export type Dir = 'x+' | 'x-' | 'z+' | 'z-';
export type RoomKind = 'battle' | 'event' | 'shop' | 'boss' | 'finale';
export type TrapPlan =
  | { kind: 'press'; delay: number } // Slams down on a timer; delay is the wait before its first warning.
  | { kind: 'belt'; dir: Dir } // Carries whatever stands on it.
  | { kind: 'valve'; dir: Dir } // Fires down the room when the hero stabs it.
  | { kind: 'pad'; text: string; heal: number; awaken?: boolean; upgrade?: boolean } // Pays out once when stepped on.
  | { kind: 'shelf'; dir: Dir; size: number; delay: number } // A bookcase size tiles long, sliding up and down the rail its mark covers. Starts at the end dir points away from.
  | { kind: 'mirror'; from: Dir; dir: Dir; delay: number } // A bolt comes from the wall on the from side, hits the mark and goes off along dir. A stab turns it the other way.
  | { kind: 'vent'; dir: Dir; delay: number } // Sends out a ring of heat with a gap in it, facing dir the first time and a quarter turn on each time after.
  | { kind: 'stamper'; dir: Dir; size: number; delay: number } // Three blows along its rail, each size tiles long, the last one late. Comes back the other way next time.
  | { kind: 'scan'; dir: Dir; delay: number } // A line sweeps the whole room along dir. The gap in it is as wide as the mark, and runs the length of the room.
  | { kind: 'erase'; delay: number } // The floor blinks out for a while, and whatever stands there is hurt until it is back.
  | { kind: 'beacon' }; // A stab brings back the nearest erased floor.
export interface Wave { count: number; hp: number; boss?: boolean; bossHp?: number; units?: EnemyKind[] }
export interface RoomPlan { id: string; kind: RoomKind; name: string; map: string[]; traps?: Record<string, TrapPlan>; waves: Wave[] }
export interface Theme { floor: number; grid: number; wall: number; trim: number; crate: number; crateTop: number }
export interface Level { name: string; theme: Theme; rooms: RoomPlan[] }

